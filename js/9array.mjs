let names = ["aarnav", "ram", "shyam", "ghanshyam"]
console.log(names);

// get array element
console.log(names[1])

// change array element
names[1] = "hari"
console.log(names[1])

// deleting a element in a array
delete names[1]
console.log(names);
// in js the space is preserved if if the element is deleted. thus, the index numbers remain same both before and after deletion
